import type { Client } from '../db/pool.js';

const OUTDATED_DAYS = { default: 90, offer: 30 };

interface Row { id: string; kind: string; name: string; norm_key: string; data: Record<string, unknown>; status: string; source_date: Date | null; source_name: string | null; origin: string }

const INFO_KEYS: Array<{ key: string; match: RegExp; ar: string; en: string }> = [
  { key: 'hours', match: /hour|open|مواعيد|ساعات|دوام|يفتح/, ar: 'ما هي مواعيد العمل؟', en: 'What are your opening hours?' },
  { key: 'address', match: /address|location|branch|عنوان|موقع|فرع/, ar: 'ما هو عنوان النشاط أو فروعه؟', en: 'What is the business address or branches?' },
  { key: 'phone', match: /phone|contact|whatsapp|call|رقم|تليفون|هاتف|تواصل|واتساب/, ar: 'ما رقم التواصل الرسمي للعملاء؟', en: 'What is the official contact number for customers?' },
  { key: 'delivery', match: /deliver|shipping|توصيل|شحن/, ar: 'هل يوجد توصيل؟ وما تكلفته؟', en: 'Do you deliver, and what does it cost?' },
  { key: 'payment', match: /payment|pay|cash|دفع|كاش|فيزا|بطاق/, ar: 'ما طرق الدفع المتاحة؟', en: 'Which payment methods do you accept?' },
];

/**
 * The smart questions for the owner. Deterministic: every question points at real rows, nothing is generated by a model.
 * subject_key is unique per company, so an answered or dismissed question is never asked again, and a question that
 * the data no longer needs is closed automatically (so the owner is not nagged about solved problems).
 */
export async function refreshQuestions(c: Client, tenantId: string): Promise<{ created: number; closed: number }> {
  const { rows } = await c.query<Row>(
    `SELECT i.id, i.kind, i.name, i.norm_key, i.data, i.status, i.source_date, i.origin, s.name AS source_name
     FROM knowledge_items i LEFT JOIN knowledge_sources s ON s.id = i.source_id WHERE i.status IN ('confirmed','unconfirmed')`,
  );
  const wanted = new Map<string, { kind: 'missing' | 'conflict' | 'outdated'; question: string; options: Record<string, unknown>; related: string[]; priority: number }>();
  const price = (r: Row) => (typeof r.data.price === 'number' ? (r.data.price as number) : null);

  // 1. missing price (only for something we show as sold)
  const byKey = new Map<string, Row[]>();
  for (const r of rows) if (r.kind === 'product' || r.kind === 'service') (byKey.get(`${r.kind}:${r.norm_key}`) ?? byKey.set(`${r.kind}:${r.norm_key}`, []).get(`${r.kind}:${r.norm_key}`)!).push(r);
  for (const [key, group] of byKey) {
    const priced = group.filter((r) => price(r) !== null);
    if (priced.length === 0) {
      const g = group[0]!;
      wanted.set(`missing_price:${key}`, { kind: 'missing', question: `ما سعر "${g.name}"؟ لم نجد سعرًا واضحًا له.`, options: { type: 'price', en: `What is the price of "${g.name}"? We found no clear price.`, name: g.name }, related: group.map((r) => r.id), priority: 70 });
      continue;
    }
    // 2. price conflict (same item, different prices)
    const prices = [...new Set(priced.map((r) => price(r)!))].sort((a, b) => a - b);
    if (prices.length > 1) {
      wanted.set(`conflict:${key}:${prices.join('|')}`, {
        kind: 'conflict',
        question: `وجدنا أكثر من سعر لـ "${priced[0]!.name}". أي سعر هو الصحيح؟`,
        options: { type: 'choose_item', en: `We found different prices for "${priced[0]!.name}". Which one is correct?`, choices: priced.map((r) => ({ itemId: r.id, price: price(r), source: r.source_name ?? (r.origin === 'owner' ? 'owner' : null), date: r.source_date })) },
        related: priced.map((r) => r.id),
        priority: 90,
      });
    }
  }
  // 3. outdated prices / offers
  const now = Date.now();
  for (const r of rows) {
    const limitDays = r.kind === 'offer' ? OUTDATED_DAYS.offer : OUTDATED_DAYS.default;
    if (!r.source_date || (r.kind !== 'offer' && price(r) === null)) continue;
    if (r.kind !== 'offer' && r.kind !== 'product' && r.kind !== 'service') continue;
    const ageDays = Math.floor((now - new Date(r.source_date).getTime()) / 86_400_000);
    if (ageDays > limitDays) {
      wanted.set(`outdated:${r.id}`, {
        kind: 'outdated',
        question: `معلومة "${r.name}" عمرها ${ageDays} يومًا. هل ما زالت صحيحة؟`,
        options: { type: 'still_valid', en: `The information about "${r.name}" is ${ageDays} days old. Is it still valid?`, ageDays },
        related: [r.id],
        priority: r.kind === 'offer' ? 60 : 50,
      });
    }
  }
  // 4. missing basics (only once the company has started adding knowledge)
  if (rows.length > 0) {
    const info = rows.filter((r) => r.kind === 'business_info');
    for (const k of INFO_KEYS) {
      if (!info.some((r) => k.match.test(`${r.name} ${r.norm_key}`.toLowerCase()))) {
        wanted.set(`missing_info:${k.key}`, { kind: 'missing', question: k.ar, options: { type: 'info', en: k.en, label: k.key }, related: [], priority: 40 });
      }
    }
  }

  let created = 0;
  for (const [subject, q] of wanted) {
    const res = await c.query(
      `INSERT INTO business_questions (tenant_id, kind, subject_key, question, options, related_item_ids, priority) VALUES ($1,$2,$3,$4,$5,$6,$7)
       ON CONFLICT (tenant_id, subject_key) DO NOTHING`,
      [tenantId, q.kind, subject, q.question, JSON.stringify(q.options), q.related, q.priority],
    );
    created += res.rowCount ?? 0;
  }
  // close open questions the data no longer needs
  const open = await c.query(`SELECT id, subject_key FROM business_questions WHERE status = 'open'`);
  let closed = 0;
  for (const o of open.rows as Array<{ id: string; subject_key: string }>) {
    if (!wanted.has(o.subject_key)) {
      await c.query(`UPDATE business_questions SET status = 'dismissed', answer = '{"auto":"no longer needed"}'::jsonb, answered_at = now() WHERE id = $1`, [o.id]);
      closed++;
    }
  }
  return { created, closed };
}
